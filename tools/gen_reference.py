#!/usr/bin/env python3
"""Generates tools/reference.txt: exp, ln, N(x) and n(x) at fixed points, from Python's `decimal`.

`decimal` computes exp and ln correctly rounded at the context precision (150 digits here);
N(x) = erfc(−x/√2)/2 uses the erf series for |z| < 3 and the erfc continued fraction beyond
(a different method from the Rust reference's positive series, cross-checked below). These
values check the arbitrary-precision reference in `optfix/tests/common/`:

    python3 tools/gen_reference.py > tools/reference.txt

Each line is `<func> <repr> <x raw> <round(f(x) × 2^160)>`, where `repr` is `bin` (x = raw /
2^64) or `dec` (x = raw / 10^18). Inputs are deterministic: edge values plus a seeded sample.
"""
import random
from decimal import Decimal as D, getcontext, ROUND_HALF_EVEN

getcontext().prec = 150
ONE = {"bin": 1 << 64, "dec": 10**18}
I128_MAX = (1 << 127) - 1


def value(repr_, raw):
    return D(raw) / D(ONE[repr_])


def fixed160(y):
    return int((y * (D(2) ** 160)).to_integral_value(ROUND_HALF_EVEN))


def pi():
    def atan_inv(n):
        x = D(1) / n
        term, total, k = x, D(0), 1
        while abs(term) > D(10) ** -140:
            total += term / k
            term *= -x * x
            k += 2
        return total
    return 16 * atan_inv(5) - 4 * atan_inv(239)


PI = pi()


def erf_series(z):
    term, total, n = z, D(0), 0
    while abs(term) > D(10) ** -140:
        total += term / (2 * n + 1)
        n += 1
        term = -term * z * z / n
    return 2 / PI.sqrt() * total


def erfc_cf(z, terms):
    # erfc(z) = e^(−z²)/√π / (z + (1/2)/(z + 1/(z + (3/2)/(z + ...)))), evaluated backwards.
    f = z
    for k in range(terms, 0, -1):
        f = z + D(k) / 2 / f
    return (-z * z).exp() / PI.sqrt() / f


def erfc(z):
    if z < 0:
        return 2 - erfc(-z)
    return 1 - erf_series(z) if z < 3 else erfc_cf(z, 20000)


def ncdf(x):
    return erfc(-x / D(2).sqrt()) / 2


def npdf(x):
    return (-x * x / 2).exp() / (2 * PI).sqrt()


def self_check():
    # The two erfc methods agree where both converge.
    for z in (D(3), D("3.5"), D(4)):
        a, b = 1 - erf_series(z), erfc_cf(z, 20000)
        assert abs(a - b) <= D(10) ** -60 * b, (z, a, b)


def points(func, repr_, rng):
    one = ONE[repr_]
    if func == "exp":
        edge = [0, 1, -1, one, -one, 43 * one, 46 * one, -41 * one, -45 * one, one // 2]
        edge += [rng.randint(-47 * one, 47 * one) for _ in range(90)]
        edge += [rng.randint(-one, one) for _ in range(30)]
        # Results must fit the reference's integer exponent; keep x where e^x is below 2^80.
        return [x for x in edge if value(repr_, x) < 55]
    if func in ("ncdf", "npdf"):
        edge = [0, 1, -1, one, -one, 5 * one, -5 * one, -8 * one, 9 * one, -(37 * one) // 4]
        edge += [rng.randint(-37 * one // 4, 37 * one // 4) for _ in range(100)]
        edge += [rng.randint(-8 * one, -5 * one) for _ in range(30)]
        return edge
    edge = [1, 2, one - 1, one, one + 1, 2 * one, one // 2, I128_MAX, 10**18, 3]
    edge += [max(1, rng.getrandbits(127) >> rng.randint(0, 126)) for _ in range(90)]
    edge += [one + rng.randint(-one // 16, one // 16) for _ in range(30)]
    return edge


def main():
    self_check()
    rng = random.Random(0x0F7F1C5E)
    print("# func repr x_raw round(f(x) * 2^160); generated by tools/gen_reference.py")
    for func in ("exp", "ln"):
        for repr_ in ("bin", "dec"):
            for x in points(func, repr_, rng):
                v = value(repr_, x)
                y = v.exp() if func == "exp" else v.ln()
                print(func, repr_, x, fixed160(y))
    # N(x) and n(x) in Q64.64 only (decided representation).
    for func, f in (("ncdf", ncdf), ("npdf", npdf)):
        for x in points(func, "bin", rng):
            print(func, "bin", x, fixed160(f(value("bin", x))))


if __name__ == "__main__":
    main()
