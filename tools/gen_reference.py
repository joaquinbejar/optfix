#!/usr/bin/env python3
"""Generates tools/reference.txt: exp and ln at fixed points, from Python's `decimal`.

`decimal` computes exp and ln correctly rounded at the context precision (150 digits here),
so these values check the arbitrary-precision reference in `optfix/tests/exp_ln_props.rs`:

    python3 tools/gen_reference.py > tools/reference.txt

Each line is `<func> <repr> <x raw> <round(f(x) × 2^160)>`, where `repr` is `bin` (x = raw /
2^64) or `dec` (x = raw / 10^18). Inputs are deterministic: edge values plus a seeded sample.
"""
import random
from decimal import Decimal as D, getcontext, ROUND_HALF_EVEN

getcontext().prec = 150
ONE = {"bin": 1 << 64, "dec": 10**18}
I128_MAX = (1 << 127) - 1


def value(repr_, raw):
    return D(raw) / D(ONE[repr_])


def fixed160(y):
    return int((y * (D(2) ** 160)).to_integral_value(ROUND_HALF_EVEN))


def points(func, repr_, rng):
    one = ONE[repr_]
    if func == "exp":
        edge = [0, 1, -1, one, -one, 43 * one, 46 * one, -41 * one, -45 * one, one // 2]
        edge += [rng.randint(-47 * one, 47 * one) for _ in range(90)]
        edge += [rng.randint(-one, one) for _ in range(30)]
        # Results must fit the reference's integer exponent; keep x where e^x is below 2^80.
        return [x for x in edge if value(repr_, x) < 55]
    edge = [1, 2, one - 1, one, one + 1, 2 * one, one // 2, I128_MAX, 10**18, 3]
    edge += [max(1, rng.getrandbits(127) >> rng.randint(0, 126)) for _ in range(90)]
    edge += [one + rng.randint(-one // 16, one // 16) for _ in range(30)]
    return edge


def main():
    rng = random.Random(0x0F7F1C5E)
    print("# func repr x_raw round(f(x) * 2^160); generated by tools/gen_reference.py")
    for func in ("exp", "ln"):
        for repr_ in ("bin", "dec"):
            for x in points(func, repr_, rng):
                v = value(repr_, x)
                y = v.exp() if func == "exp" else v.ln()
                print(func, repr_, x, fixed160(y))


if __name__ == "__main__":
    main()
